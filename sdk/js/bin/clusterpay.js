#!/usr/bin/env node

/**
 * ⚡ ClusterPay Node.js CLI Toolkit
 * Run:
 *   npx clusterpay setup
 *   npx clusterpay version
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const readline = require('readline');

function generateBase32(length = 32) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  let out = '';
  const bytes = crypto.randomBytes(length);
  for (let i = 0; i < length; i++) {
    out += alphabet[bytes[i] % 32];
  }
  return out;
}

function prompt(question) {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });
  return new Promise(resolve => {
    rl.question(question, answer => {
      rl.close();
      resolve(answer.trim());
    });
  });
}

async function setup() {
  const adminKey = crypto.randomBytes(30).toString('base64url');
  const totpSecret = generateBase32(32);
  const mongoRootPw = crypto.randomBytes(18).toString('base64url');
  const mongoAppPw = crypto.randomBytes(18).toString('base64url');

  const otpUri = `otpauth://totp/ClusterPay%20Admin:admin@clusterpay?secret=${totpSecret}&issuer=ClusterPay%20Admin`;

  console.log();
  console.log('='.repeat(64));
  console.log('   🔐  ClusterPay Security & 2FA Setup');
  console.log('='.repeat(64));
  console.log();
  console.log('  ✅  ADMIN_MASTER_KEY  (admin console login password):');
  console.log(`      ${adminKey}`);
  console.log();
  console.log('  ✅  ADMIN_TOTP_SECRET  (2FA — add to authenticator app):');
  console.log(`      ${totpSecret}`);
  console.log();
  console.log('  ✅  MONGO_ROOT_PASSWORD  (MongoDB root admin):');
  console.log(`      ${mongoRootPw}`);
  console.log();
  console.log('  ✅  MONGO_PASSWORD  (MongoDB app user for gateway):');
  console.log(`      ${mongoAppPw}`);
  console.log();
  console.log('  🌐  Add manually on https://2fa.live or Google Authenticator:');
  console.log(`      Secret Key: ${totpSecret}`);
  console.log(`      OTP URI:    ${otpUri}`);
  console.log();
  console.log('='.repeat(64));
  console.log('  📋  Configuration Template:');
  console.log();
  console.log(`      ADMIN_MASTER_KEY=${adminKey}`);
  console.log(`      ADMIN_TOTP_SECRET=${totpSecret}`);
  console.log(`      MONGO_ROOT_PASSWORD=${mongoRootPw}`);
  console.log(`      MONGO_PASSWORD=${mongoAppPw}`);
  console.log('='.repeat(64));
  console.log();

  const envPath = path.join(process.cwd(), '.env');
  if (fs.existsSync(envPath)) {
    const ans = await prompt(`  .env already exists. Append keys to ${envPath}? [y/N]: `);
    if (ans.toLowerCase() === 'y') {
      const content = `\n# Generated by clusterpay setup\nADMIN_MASTER_KEY=${adminKey}\nADMIN_TOTP_SECRET=${totpSecret}\nMONGO_ROOT_PASSWORD=${mongoRootPw}\nMONGO_PASSWORD=${mongoAppPw}\n`;
      fs.appendFileSync(envPath, content, 'utf8');
      console.log(`  ✅ Appended credentials to ${envPath}`);
    }
  } else {
    const ans = await prompt(`  Create .env file at ${envPath}? [Y/n]: `);
    if (ans.toLowerCase() !== 'n') {
      const content = `# ClusterPay Node Environment
HOST=0.0.0.0
PORT=8085
BASE_URL=https://pay.yourstore.com
ENVIRONMENT=production
ADMIN_MASTER_KEY=${adminKey}
ADMIN_TOTP_SECRET=${totpSecret}
MONGO_ROOT_PASSWORD=${mongoRootPw}
MONGO_PASSWORD=${mongoAppPw}
MONGO_URI=mongodb://cpay_user:${mongoAppPw}@127.0.0.1:27017/clusterpay_db?authSource=clusterpay_db
MONGO_DB_NAME=clusterpay_db
RATE_LIMIT_PER_MINUTE=60
`;
      fs.writeFileSync(envPath, content, 'utf8');
      console.log(`  ✅ Written new .env to ${envPath}`);
    }
  }

  console.log();
  console.log("  🚀 Next Step: Run 'docker compose up -d'");
  console.log();
}

const args = process.argv.slice(2);
const cmd = args[0] || 'help';

if (cmd === 'setup' || cmd === 'init') {
  setup();
} else if (cmd === 'version' || cmd === '-v' || cmd === '--version') {
  const pkg = require('../package.json');
  console.log(`ClusterPay Node.js SDK & CLI v${pkg.version}`);
} else {
  console.log(`
ClusterPay CLI

Usage:
  npx clusterpay setup     Generate Admin Master Key, 2FA TOTP secret & .env
  npx clusterpay version   Show version info
`);
}
